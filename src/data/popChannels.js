// Helper functions for pop channel filtering
export const getPopChannelsByTag = tag => {
  return popChannels.filter(channel =>
    channel.tags.some(t => t.toLowerCase().includes(tag.toLowerCase()))
  );
};

export const getPopularPopChannels = () => {
  return popChannels.filter(channel => channel.isPopular);
};

export const getNewPopChannels = () => {
  return popChannels.filter(channel => channel.isNew);
};

export const getTopPopChannelsByPlays = (limit = 10) => {
  return [...popChannels].sort((a, b) => b.playCount - a.playCount).slice(0, limit);
};

export const getPopChannelsByPlayCountRange = (min, max) => {
  return popChannels.filter(channel => channel.playCount >= min && channel.playCount <= max);
};
